/** 文本的全拼（无空格）和声母串，供素材名近似搜索。 */
export function textPinyin(text: string): { readonly full: string; readonly initials: string } {
  let full = '';
  let initials = '';
  for (const char of text) {
    const py = PINYIN[char];
    if (!py) {
      continue;
    }
    full += py;
    initials += py[0] ?? '';
  }
  return { full, initials };
}
